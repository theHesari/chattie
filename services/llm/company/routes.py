"""Dashboard API: a user's character, history, requests and (for managers) team.

The employee always comes from the verified token, never from the request. Reads go through the
read-only role with row-level security (the same rules as the chatbot); requests are filed through
the `chattie_app` role; characters are generated by the `chattie_generator` role in a worker thread.
"""

import asyncio
from contextlib import asynccontextmanager
from datetime import date, time, timedelta
from typing import Annotated, Any
from uuid import UUID

from fastapi import APIRouter, Depends, HTTPException, Request
from psycopg import sql
from pydantic import BaseModel, ConfigDict, Field
from pydantic.alias_generators import to_camel

from company.characters import CharacterCapExceeded, CharacterOut, Role, replace_character
from company.clock import company_today
from company.leave_rules import Kind, NoActiveCharacter, RequestIn, RequestNotFound, cancel_request, leave_balance, submit_request
from company.service import ensure_character
from core_llm.auth import CurrentUserId

router = APIRouter(tags=["company"])

CHARACTER_CHANGED = "your character changed while this was running: reload and try again"


class CamelModel(BaseModel):
    model_config = ConfigDict(alias_generator=to_camel, populate_by_name=True)


class CharacterIn(CamelModel):
    display_name: str
    role: Role
    department_id: int | None = None


class CharacterView(CamelModel):
    employee_id: int
    name: str
    title: str
    role: str
    department: str
    manager_name: str | None


class RequestBody(CamelModel):
    """What a client may send. Anything else (for example an employee id) is ignored."""

    kind: Kind
    starts_on: date
    ends_on: date | None = None
    start_time: time | None = None
    end_time: time | None = None
    hours: float | None = Field(default=None, ge=0.25, le=24, allow_inf_nan=False)
    reason: str | None = Field(default=None, max_length=500)
    request_key: UUID


class ResultView(CamelModel):
    id: int | None
    status: str
    decision_reason: str
    balance_after: int | None = None


class RequestView(CamelModel):
    id: int
    kind: str
    starts_on: date
    ends_on: date
    start_time: time | None
    end_time: time | None
    hours: float | None
    reason: str | None
    status: str
    decision_reason: str
    created_at: str


class EventView(CamelModel):
    happened_at: str
    kind: str
    title: str
    details: dict[str, Any]


class BalanceView(CamelModel):
    year: int
    allowance: int
    used: int
    remaining: int


class WorkDayView(CamelModel):
    day: date
    hours: float
    kind: str


class HistoryView(CamelModel):
    today: date
    events: list[EventView]
    balance: BalanceView
    recent_work_days: list[WorkDayView]


class TeamMemberView(CamelModel):
    id: int
    name: str
    title: str
    today_status: str | None
    next_away: date | None


def get_today(request: Request) -> date:
    return company_today(request.app.state.settings)


Today = Annotated[date, Depends(get_today)]


def _view(character: CharacterOut) -> CharacterView:
    return CharacterView(**character.model_dump())


async def _ensure(request: Request, user_id: str, today: date) -> CharacterOut | None:
    pool = getattr(request.app.state, "generator_pool", None)
    if pool is None:
        raise HTTPException(503, "company features are not configured on this server")
    return await asyncio.to_thread(ensure_character, pool, user_id, today)


async def require_character(request: Request, user_id: CurrentUserId, today: Today) -> CharacterOut:
    character = await _ensure(request, user_id, today)
    if character is None:
        raise HTTPException(409, "you have no character yet: create one first (POST /character)")
    return character


Character = Annotated[CharacterOut, Depends(require_character)]


@asynccontextmanager
async def as_user(pool, user_id: str):
    """A transaction in which row-level security sees `user_id` (the same way the SQL tool sets it)."""
    async with pool.connection() as conn, conn.transaction():
        await conn.execute(sql.SQL("SET LOCAL app.user_id = {}").format(sql.Literal(user_id)))
        yield conn


def _limit(request: Request, limiter_name: str, user_id: str) -> None:
    limiter = getattr(request.app.state, limiter_name)
    if not limiter.allow(user_id):
        raise HTTPException(429, "too many requests: try again later", headers={"Retry-After": str(limiter.retry_after(user_id))})


def _pool(request: Request, name: str):
    pool = getattr(request.app.state, name, None)
    if pool is None:
        raise HTTPException(503, "company features are not configured on this server")
    return pool


# --- character ----------------------------------------------------------------------------------------


@router.post("/character", response_model=CharacterView, summary="Create (or replace) your character")
async def create_character(request: Request, body: CharacterIn, user_id: CurrentUserId, today: Today) -> CharacterView:
    pool = _pool(request, "generator_pool")
    _limit(request, "character_limiter", user_id)

    def generate() -> CharacterOut:
        with pool.connection() as conn:
            return replace_character(conn, user_id=user_id, display_name=body.display_name, role=body.role,
                                     department_id=body.department_id, today=today)

    try:
        return _view(await asyncio.to_thread(generate))
    except CharacterCapExceeded as exc:
        raise HTTPException(409, str(exc)) from None
    except ValueError as exc:
        raise HTTPException(422, str(exc)) from None


@router.get("/me", response_model=CharacterView | None, summary="Your character, or null")
async def me(request: Request, user_id: CurrentUserId, today: Today) -> CharacterView | None:
    character = await _ensure(request, user_id, today)
    return _view(character) if character else None


# --- history and requests -----------------------------------------------------------------------------


@router.get("/me/history", response_model=HistoryView, summary="Timeline, leave balance and recent work days")
async def history(request: Request, user_id: CurrentUserId, character: Character, today: Today) -> HistoryView:
    async with as_user(_pool(request, "query_pool"), user_id) as conn:
        events = await (await conn.execute(
            "SELECT happened_at, kind, title, details FROM company.employee_events WHERE employee_id = %s "
            "ORDER BY happened_at DESC LIMIT 50", (character.employee_id,))).fetchall()
        try:
            allowance, used = await leave_balance(conn, character.employee_id, today.year)
        except NoActiveCharacter:
            raise HTTPException(409, CHARACTER_CHANGED) from None
        days = await (await conn.execute(
            "SELECT day, hours, kind FROM company.work_days WHERE employee_id = %s AND day > %s AND day <= %s "
            "ORDER BY day DESC", (character.employee_id, today - timedelta(days=30), today))).fetchall()
    return HistoryView(
        today=today,
        events=[EventView(happened_at=e[0].isoformat(), kind=e[1], title=e[2], details=e[3]) for e in events],
        balance=BalanceView(year=today.year, allowance=allowance, used=used, remaining=allowance - used),
        recent_work_days=[WorkDayView(day=d[0], hours=float(d[1]), kind=d[2]) for d in days],
    )


@router.get("/me/requests", response_model=list[RequestView], summary="Your requests, newest first")
async def list_requests(request: Request, user_id: CurrentUserId, character: Character) -> list[RequestView]:
    async with as_user(_pool(request, "query_pool"), user_id) as conn:
        rows = await (await conn.execute(
            "SELECT id, kind, starts_on, ends_on, start_time, end_time, hours, reason, status, decision_reason, created_at "
            "FROM company.employee_requests WHERE employee_id = %s ORDER BY created_at DESC, id DESC LIMIT 50",
            (character.employee_id,))).fetchall()
    return [RequestView(id=r[0], kind=r[1], starts_on=r[2], ends_on=r[3], start_time=r[4], end_time=r[5],
                        hours=float(r[6]) if r[6] is not None else None, reason=r[7], status=r[8],
                        decision_reason=r[9], created_at=r[10].isoformat()) for r in rows]


@router.post("/me/requests", response_model=ResultView, summary="File a request; it is decided immediately")
async def file_request(request: Request, body: RequestBody, user_id: CurrentUserId, character: Character, today: Today) -> ResultView:
    _limit(request, "request_limiter", user_id)
    async with as_user(_pool(request, "app_pool"), user_id) as conn:
        try:
            result = await submit_request(conn, character.employee_id, RequestIn(**body.model_dump()), today)
        except NoActiveCharacter:
            raise HTTPException(409, CHARACTER_CHANGED) from None
    if result.id is None:  # malformed: nothing was stored
        raise HTTPException(422, result.decision_reason)
    return ResultView(**result.model_dump())


@router.post("/me/requests/{request_id}/cancel", response_model=ResultView, summary="Cancel one of your approved requests")
async def cancel(request: Request, request_id: int, user_id: CurrentUserId, character: Character, today: Today) -> ResultView:
    async with as_user(_pool(request, "app_pool"), user_id) as conn:
        try:
            result = await cancel_request(conn, character.employee_id, request_id, today)
        except RequestNotFound:
            raise HTTPException(404, "request not found") from None
        except NoActiveCharacter:
            raise HTTPException(409, CHARACTER_CHANGED) from None
    return ResultView(**result.model_dump())


# --- team ---------------------------------------------------------------------------------------------


@router.get("/team", response_model=list[TeamMemberView], summary="Your direct reports (managers only)")
async def team(request: Request, user_id: CurrentUserId, character: Character, today: Today) -> list[TeamMemberView]:
    if character.role != "manager":
        raise HTTPException(403, "only managers have a team")
    async with as_user(_pool(request, "query_pool"), user_id) as conn:
        rows = await (await conn.execute(
            "SELECT e.id, e.name, e.title, "
            "  (SELECT w.kind FROM company.work_days w WHERE w.employee_id = e.id AND w.day = %s), "
            "  (SELECT min(r.starts_on) FROM company.employee_requests r WHERE r.employee_id = e.id "
            "     AND r.status = 'approved' AND r.kind IN ('day_off', 'sick_day') AND r.ends_on >= %s) "
            "FROM company.employees e WHERE e.manager_id = %s ORDER BY e.name",
            (today, today, character.employee_id))).fetchall()
    return [TeamMemberView(id=r[0], name=r[1], title=r[2], today_status=r[3], next_away=r[4]) for r in rows]
